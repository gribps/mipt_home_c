#include <stdio.h>

int main() {
    // Массивы для хранения найденных комбинаций
    char seen1[10] = {0};
    char seen2[10][10] = {{0}};
    char seen3[10][10][10] = {{{0}}};
    
    int ch;
    // Посимвольное чтение до конца строки или файла
    while ((ch = getchar()) != EOF && ch != '\n') {
        if (ch >= '0' && ch <= '9') {
            int c = ch - '0';
            
            // 1. Фиксируем новые трехзначные числа
            for (int d1 = 1; d1 <= 9; d1++) {
                for (int d2 = 0; d2 <= 9; d2++) {
                    if (seen2[d1][d2]) {
                        seen3[d1][d2][c] = 1;
                    }
                }
            }
            
            // 2. Фиксируем новые двузначные пары
            for (int d1 = 1; d1 <= 9; d1++) {
                if (seen1[d1]) {
                    seen2[d1][c] = 1;
                }
            }
            
            // 3. Фиксируем первую цифру (без ведущих нулей)
            if (c > 0) {
                seen1[c] = 1;
            }
        }
    }
    
    // Подсчитываем количество уникальных трехзначных чисел
    int count = 0;
    for (int d1 = 1; d1 <= 9; d1++) {
        for (int d2 = 0; d2 <= 9; d2++) {
            for (int d3 = 0; d3 <= 9; d3++) {
                if (seen3[d1][d2][d3]) {
                    count++;
                }
            }
        }
    }
    
    printf("%d\n", count);
    return 0;
}